package org.example;

public class Penguin {

    private String name;
    private int age;

    public Penguin() {
    }

    public Penguin(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }
}